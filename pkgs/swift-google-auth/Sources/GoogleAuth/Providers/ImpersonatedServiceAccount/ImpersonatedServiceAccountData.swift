import GoogleWKT

/// Represents the raw `impersonated_service_account` JSON credential file format generated by
/// `gcloud auth application-default login --impersonate-service-account=<email>`.
///
/// - SeeAlso: [AIP-4110: Application Default Credentials](https://google.aip.dev/auth/4110)
struct ImpersonatedServiceAccountData: Sendable, Codable {
  let type: String
  let serviceAccountImpersonationUrl: String
  let sourceCredentials: WKTStruct
  let delegates: [String]?
  let quotaProjectId: String?
  let universeDomain: String?

  enum CodingKeys: String, CodingKey {
    case type
    case serviceAccountImpersonationUrl = "service_account_impersonation_url"
    case sourceCredentials = "source_credentials"
    case delegates
    case quotaProjectId = "quota_project_id"
    case universeDomain = "universe_domain"
  }
}
