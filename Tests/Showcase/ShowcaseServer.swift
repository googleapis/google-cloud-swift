import Foundation
import NIOSSL

// For POSIX `kill(_:_:)` / `SIGKILL` fallback when stopping the Showcase subprocess.
#if canImport(Glibc)
  import Glibc
#elseif canImport(Darwin)
  import Darwin
#endif

/// Manages an ephemeral `gapic-showcase` mock server process running with Auto-TLS (`--tls`).
///
/// Each server binds to an OS-assigned loopback port (`--port :0`), generates an in-memory CA and
/// server certificate, writes the CA PEM to a temporary directory, and optionally pins the server's
/// accepted TLS key-exchange groups via `--tls-groups` (such as `0x11ec` for `X25519MLKEM768`).
/// Use ``withServer(tlsGroups:_:)`` to run a test closure against a started server and ensure the
/// subprocess and temporary files are cleaned up on exit.
final class ShowcaseServer: Sendable {
  /// The HTTPS base URL (e.g., `"https://localhost:12345"`) where Showcase is listening.
  let endpoint: String

  /// The PEM-encoded root CA certificate generated by Showcase for this server instance.
  let caCertPEM: String

  private let process: Process
  private let tempDir: URL
  private let logHandle: FileHandle

  private init(
    endpoint: String,
    caCertPEM: String,
    process: Process,
    tempDir: URL,
    logHandle: FileHandle
  ) {
    self.endpoint = endpoint
    self.caCertPEM = caCertPEM
    self.process = process
    self.tempDir = tempDir
    self.logHandle = logHandle
  }

  private func stop() async {
    await Self.terminateProcess(self.process)
    try? self.logHandle.close()
    try? FileManager.default.removeItem(at: self.tempDir)
  }

  /// Terminates `process` asynchronously without blocking Swift's cooperative thread pool.
  ///
  /// Sends `SIGTERM` first and polls `isRunning` for up to 5 seconds. Because `gapic-showcase`
  /// handles `SIGTERM` by draining open HTTP/1.1 connections without a deadline, escalates to
  /// `SIGKILL` if the process does not exit within the grace period (or if the task is cancelled).
  private static func terminateProcess(_ process: Process) async {
    guard process.isRunning else { return }
    process.terminate()

    let graceDeadline = ContinuousClock.now.advanced(by: .seconds(5))
    while process.isRunning && ContinuousClock.now < graceDeadline {
      do {
        try await Task.sleep(for: .milliseconds(50))
      } catch {
        break
      }
    }

    if process.isRunning {
      _ = kill(process.processIdentifier, SIGKILL)
      let killDeadline = ContinuousClock.now.advanced(by: .seconds(1))
      while process.isRunning && ContinuousClock.now < killDeadline {
        do {
          try await Task.sleep(for: .milliseconds(50))
        } catch {
          break
        }
      }
    }
  }

  /// Returns a ``ShowcaseHTTPClient`` configured to trust this server's CA certificate over
  /// HTTP/1.1, optionally overriding the client's offered TLS key-exchange `curves`.
  func makeHTTPClient(curves: [NIOTLSCurve]? = nil) throws -> ShowcaseHTTPClient {
    try ShowcaseHTTPClient(caCertPEM: self.caCertPEM, curves: curves)
  }

  /// Starts a `gapic-showcase` server with Auto-TLS, executes `body`, and stops the server when
  /// `body` returns or throws.
  ///
  /// - Parameters:
  ///   - tlsGroups: TLS key-exchange groups passed to `--tls-groups` as hex IANA codepoints
  ///     (defaults to `[.x25519_MLKEM768]`), or `nil` to leave server groups unpinned.
  ///   - body: The test closure to run against the started server.
  static func withServer(
    tlsGroups: [NIOTLSCurve]? = [.x25519_MLKEM768],
    _ body: (ShowcaseServer) async throws -> Void
  ) async throws {
    let server = try await Self.start(tlsGroups: tlsGroups)
    do {
      try await body(server)
    } catch {
      await server.stop()
      throw error
    }
    await server.stop()
  }

  /// Launches a `gapic-showcase` subprocess with Auto-TLS and waits until it is ready to serve
  /// HTTPS requests.
  ///
  /// Startup proceeds in three phases:
  /// 1. Create a private temporary directory for Showcase's generated CA PEM and combined log file.
  /// 2. Spawn `gapic-showcase run` on OS-assigned loopback ports (`:0`) with `--tls`, optional
  ///    `--tls-groups`, and proxy environment variables cleared.
  /// 3. Poll until the full CA PEM certificate is written, the bound HTTPS endpoint is logged, and
  ///    Showcase reports that its REST listener is accepting connections.
  private static func start(tlsGroups: [NIOTLSCurve]?) async throws -> ShowcaseServer {
    let binary = try findBinary()

    // Prepare an isolated temporary directory for the ephemeral CA certificate and server logs.
    let tempDir = FileManager.default.temporaryDirectory
      .appendingPathComponent(
        "showcase_\(ProcessInfo.processInfo.processIdentifier)_\(UUID().uuidString)",
        isDirectory: true
      )
    try FileManager.default.createDirectory(
      at: tempDir,
      withIntermediateDirectories: true,
      attributes: [.posixPermissions: 0o700]
    )
    let tempCAFile = tempDir.appendingPathComponent("ca.pem")
    let logFile = tempDir.appendingPathComponent("showcase.log")
    _ = FileManager.default.createFile(
      atPath: logFile.path,
      contents: nil,
      attributes: [.posixPermissions: 0o600]
    )
    let logHandle: FileHandle
    do {
      logHandle = try FileHandle(forWritingTo: logFile)
    } catch {
      try? FileManager.default.removeItem(at: tempDir)
      throw error
    }

    // Configure and spawn `gapic-showcase run` with Auto-TLS on ephemeral ports.
    let process = Process()
    process.executableURL = URL(fileURLWithPath: binary)
    var args = [
      "run",
      "--port", ":0",
      "--fallback-port", ":0",
      "--tls",
      "--ca-cert-output-file", tempCAFile.path,
    ]
    if let tlsGroups, !tlsGroups.isEmpty {
      // Showcase's `--tls-groups` expects numeric IANA codepoints (e.g. hex `0x11ec`), which
      // `NIOTLSCurve.rawValue` provides.
      let formatted = tlsGroups.map { "0x\(String($0.rawValue, radix: 16))" }.joined(
        separator: ",")
      args.append(contentsOf: ["--tls-groups", formatted])
    }
    process.arguments = args

    // Clear proxy variables so local connections in Showcase or child tools do not route via proxy.
    var env = ProcessInfo.processInfo.environment
    env["NO_PROXY"] = "localhost,127.0.0.1"
    env["no_proxy"] = "localhost,127.0.0.1"
    env.removeValue(forKey: "HTTP_PROXY")
    env.removeValue(forKey: "HTTPS_PROXY")
    env.removeValue(forKey: "http_proxy")
    env.removeValue(forKey: "https_proxy")
    process.environment = env
    process.standardInput = FileHandle.nullDevice
    process.standardOutput = logHandle
    process.standardError = logHandle

    do {
      try process.run()
    } catch {
      try? logHandle.close()
      try? FileManager.default.removeItem(at: tempDir)
      throw error
    }

    // Poll until Showcase writes the complete CA certificate, logs the bound TLS port, and starts
    // serving HTTP/REST connections on the listener.
    let startupDeadline = ContinuousClock.now.advanced(by: .seconds(30))
    var resolvedEndpoint: String?
    var resolvedCACert: String?
    var restListening = false

    while ContinuousClock.now < startupDeadline {
      if !process.isRunning {
        let logOutput = (try? String(contentsOf: logFile, encoding: .utf8)) ?? ""
        try? logHandle.close()
        try? FileManager.default.removeItem(at: tempDir)
        throw ShowcaseServerError.startupTimeout("Showcase exited early: \(logOutput)")
      }
      if resolvedCACert == nil,
        let content = try? String(contentsOf: tempCAFile, encoding: .utf8),
        content.contains("-----BEGIN CERTIFICATE-----"),
        content.contains("-----END CERTIFICATE-----")
      {
        resolvedCACert = content
      }
      if let logOutput = try? String(contentsOf: logFile, encoding: .utf8) {
        if resolvedEndpoint == nil,
          let match = logOutput.firstMatch(
            of: /HTTP\/REST Endpoint \(TLS\): (https:\/\/localhost:\d+)/)
        {
          resolvedEndpoint = String(match.1)
        }
        if !restListening && logOutput.contains("Listening for REST connections") {
          restListening = true
        }
      }
      if resolvedCACert != nil && resolvedEndpoint != nil && restListening {
        break
      }
      try await Task.sleep(for: .milliseconds(50))
    }

    guard let endpoint = resolvedEndpoint, let caCert = resolvedCACert, restListening else {
      let logOutput = (try? String(contentsOf: logFile, encoding: .utf8)) ?? ""
      await terminateProcess(process)
      try? logHandle.close()
      try? FileManager.default.removeItem(at: tempDir)
      throw ShowcaseServerError.startupTimeout(logOutput)
    }

    return ShowcaseServer(
      endpoint: endpoint,
      caCertPEM: caCert,
      process: process,
      tempDir: tempDir,
      logHandle: logHandle
    )
  }

  private static func findBinary() throws -> String {
    guard let path = ProcessInfo.processInfo.environment["GOOGLE_CLOUD_SWIFT_SHOWCASE_PATH"],
      FileManager.default.isExecutableFile(atPath: path)
    else {
      throw ShowcaseServerError.binaryNotFound
    }
    return path
  }
}
